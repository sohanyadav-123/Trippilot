/**
 * Normalizes input name for dictionary lookup (lowercased, trimmed, stripped of airport codes or trailing details)
 */
export function normalizePlaceKey(rawName: string): string {
  if (!rawName) return '';
  return rawName
    .toLowerCase()
    .replace(/\s*\([a-z0-9]+\)\s*/gi, '') // remove (HYD), (GOI), etc.
    .replace(/,\s*india/gi, '')
    .replace(/,\s*uae/gi, '')
    .replace(/,\s*himachal/gi, '')
    .replace(/,\s*indonesia/gi, '')
    .replace(/,\s*france/gi, '')
    .trim();
}

/**
 * Translates a single place, city, country or airline into the target language.
 */
export function translatePlace(name: string, lang: LanguageCode): string {
  if (!name || lang === 'en') return name;

  const key = normalizePlaceKey(name);
  const entry = PLACE_TRANSLATIONS[key];

  if (entry && entry[lang]) {
    // Preserve airport code if original had one, e.g. "Hyderabad (HYD)" -> "हैदराबाद (HYD)"
    const codeMatch = name.match(/\(([A-Z0-9]{3,4})\)/);
    if (codeMatch) {
      return `${entry[lang]} (${codeMatch[1]})`;
    }
    return entry[lang]!;
  }

  return name;
}

/**
 * Translates route strings such as "Hyderabad (HYD) → Goa (GOI)" or "Delhi to Mumbai"
 */
export function translateRoute(routeStr: string, lang: LanguageCode): string {
  if (!routeStr || lang === 'en') return routeStr;

  if (routeStr.includes('→')) {
    const parts = routeStr.split('→');
    return parts.map((p) => translatePlace(p.trim(), lang)).join(' → ');
  }

  if (routeStr.includes(' to ')) {
    const parts = routeStr.split(' to ');
    const translatedSeparator = lang === 'hi' ? ' से ' : ' to ';
    return parts.map((p) => translatePlace(p.trim(), lang)).join(translatedSeparator);
  }

  return translatePlace(routeStr, lang);
}
