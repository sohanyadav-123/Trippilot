/**
 * Filter locations by query with fuzzy matching on city, airport code, airport name, or state.
 */
export function searchLocations(query: string, filterType?: 'airport' | 'railway_station' | 'bus_station' | 'destination'): LocationItem[] {
  const q = query.trim().toLowerCase();
  if (!q) {
    return LOCATIONS_DATA;
  }

  return LOCATIONS_DATA.filter((item) => {
    const matchCity = item.city.toLowerCase().includes(q);
    const matchState = item.state.toLowerCase().includes(q);
    const matchCountry = item.country.toLowerCase().includes(q);
    const matchCode = item.airportCode?.toLowerCase().includes(q) || item.stationCode?.toLowerCase().includes(q);
    const matchAirport = item.airportName?.toLowerCase().includes(q);
    const matchStation = item.stationName?.toLowerCase().includes(q);

    return matchCity || matchState || matchCountry || matchCode || matchAirport || matchStation;
  });
}
